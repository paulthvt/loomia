// What goes to FCM, and what its answer means. Pure, so handler_test.ts pins
// it without a network.

/** An FCM HTTP v1 request body. */
export type Message = { message: { token: string } }

/**
 * The daily summary: a loc key and its arguments, never text. [tasks] is
 * counted since #377; a phone whose app predates it ([withTasks] false) gets
 * the people-only sentence, and nothing when only tasks are due, so it never
 * reads "0 people".
 */
export function summaryMessage(
  token: string,
  locale: string,
  people: number,
  tasks = 0,
  withTasks = false,
) {
  // The phone renders it from strings generated by tool/push_strings.dart, in
  // the app's language on that device: always one the installed app ships.
  // ponytail: one/other only, right for en and fr. A language with more
  // plural forms needs CLDR rules here and in the tool.
  const form = (n: number) => (n === 1 ? 'one' : 'other')
  let key: string
  let args: string[]
  if (!withTasks || tasks === 0) {
    if (people === 0) return null
    key = `push_summary_body_${form(people)}_${locale}`
    args = [String(people)]
  } else if (people === 0) {
    key = `push_summary_tasks_${form(tasks)}_${locale}`
    args = [String(tasks)]
  } else {
    key = `push_summary_both_${form(people)}_${form(tasks)}_${locale}`
    // Only the "other" counts are in the sentence; "one" is a word.
    args = [
      ...(people === 1 ? [] : [String(people)]),
      ...(tasks === 1 ? [] : [String(tasks)]),
    ]
  }
  return {
    message: {
      token,
      // A tap opens Today; no name or other personal data, as it shows on a
      // locked phone.
      data: { type: 'daily_summary' },
      android: { notification: { body_loc_key: key, body_loc_args: args } },
      apns: {
        payload: { aps: { alert: { 'loc-key': key, 'loc-args': args } } },
      },
    },
  }
}

/** claim_task_alerts(): one open task whose time has come (#377). */
export type TaskClaim = {
  owner_id: string
  task_id: string
  title: string
  note: string | null
  alerted_for: string
}

/**
 * A task's push: her own words, so literal text, not a loc key. A tap opens
 * the task's sheet.
 */
export function taskMessage(token: string, claim: TaskClaim) {
  const notification = claim.note
    ? { title: claim.title, body: claim.note }
    : { title: claim.title }
  return {
    message: {
      token,
      data: { type: 'task', task: claim.task_id },
      notification,
    },
  }
}

/**
 * claim_month_rituals(): the months as `YYYY-MM-01`, and the date the claim
 * is filed under, one per half of the window (#354).
 */
export type RitualClaim = {
  owner_id: string
  to_close: string
  to_plan: string
  closes: boolean
  claim_date: string
}

/**
 * "October", "octobre": what Dart's MMMM gives the card. A month name is
 * data, not copy, so it travels as an argument. UTC on both sides, so no
 * zone moves the 1st into another month.
 */
export function monthName(date: string, locale: string) {
  return new Intl.DateTimeFormat(locale, { month: 'long', timeZone: 'UTC' })
    .format(new Date(`${date}T00:00:00Z`))
}

/**
 * The month-end push: Today's close-and-plan card, title and body, from the
 * same keys (pushRitual* in the ARB files).
 */
export function ritualMessage(
  token: string,
  locale: string,
  claim: RitualClaim,
) {
  const plan = monthName(claim.to_plan, locale)
  const [titleKey, titleArgs, bodyKey, bodyArgs] = claim.closes
    ? [
      `push_ritual_title_${locale}`,
      [monthName(claim.to_close, locale), plan],
      `push_ritual_body_${locale}`,
      [plan],
    ]
    : [
      `push_ritual_plan_title_${locale}`,
      [plan],
      `push_ritual_plan_body_${locale}`,
      [],
    ]
  return {
    message: {
      token,
      data: { type: 'month_ritual' },
      android: {
        notification: {
          title_loc_key: titleKey,
          title_loc_args: titleArgs,
          body_loc_key: bodyKey,
          body_loc_args: bodyArgs,
        },
      },
      apns: {
        payload: {
          aps: {
            alert: {
              'title-loc-key': titleKey,
              'title-loc-args': titleArgs,
              'loc-key': bodyKey,
              'loc-args': bodyArgs,
            },
          },
        },
      },
    },
  }
}

/**
 * sent: FCM accepted it (not proof it was shown). drop: the token is dead.
 * retry: worth another run. failed: our bug (a bad payload, credentials);
 * retrying won't help, so it is logged and the day kept.
 */
export type Outcome = 'sent' | 'drop' | 'retry' | 'failed'

type FcmError = {
  error?: {
    status?: string
    details?: {
      errorCode?: string
      fieldViolations?: { field?: string }[]
    }[]
  }
}

export function outcome(status: number, body: unknown): Outcome {
  if (status >= 200 && status < 300) return 'sent'
  if (status === 429 || status >= 500) return 'retry'
  const details = (body as FcmError | null)?.error?.details ?? []
  const codes = details.map((d) => d.errorCode)
  if (codes.includes('UNREGISTERED') || codes.includes('SENDER_ID_MISMATCH')) {
    return 'drop'
  }
  // INVALID_ARGUMENT is also a bad payload: only a violation on the token
  // itself means the token is dead.
  const badToken = details.some((d) =>
    d.fieldViolations?.some((v) => v.field === 'message.token')
  )
  return badToken ? 'drop' : 'failed'
}
