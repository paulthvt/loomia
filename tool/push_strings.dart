// The push copy, from the ARB files into the strings the phone renders a push
// with (FCM `body_loc_key`, APNs `loc-key`):
//
//   dart run tool/push_strings.dart
//
// Every `push*` key of every language goes into one file per platform, its
// name suffixed with the plural form and the language
// (`push_summary_body_other_fr`): the sender picks the key, so the push follows
// the language chosen in the app, not only the phone's. Run by the l10n sync;
// test/tool/push_strings_test.dart fails when the committed files are stale.
// res/raw/push_keep.xml keeps them through release resource shrinking.
//
// A whole-message plural becomes `_one` (`=1`, `one`) and `_other`; anything
// else (`=0`, `few`…) stops the run. Literal `%` is `%%`: the sender always
// passes arguments, so the OS always formats.
// ponytail: one/other only, right for en and fr. A language with more plural
// forms needs CLDR rules in the sender and here.
import 'dart:convert';
import 'dart:io';

const androidPath = 'android/app/src/main/res/values/push_strings.xml';
const iosPath = 'ios/Runner/Localizable.strings';

/// A message as literal text (`String`) and 1-based argument positions (`int`).
typedef Parts = List<Object>;

/// Native key → message, sorted by key, from ARB contents by language.
/// Placeholder positions follow the English `@key.placeholders` order.
Map<String, Parts> pushStrings(Map<String, Map<String, dynamic>> arbs) {
  final english = arbs['en'] ?? const <String, dynamic>{};
  final result = <String, Parts>{};
  for (final MapEntry(key: locale, value: arb) in arbs.entries) {
    // A key the language lacks yet (until the l10n sync) goes in English, so
    // the sender's key always exists on the phone.
    for (final MapEntry(:key, :value) in {...english, ...arb}.entries) {
      if (!key.startsWith('push') || value is! String) continue;
      final meta = (english['@$key'] ?? arb['@$key']) as Map<String, dynamic>?;
      final names = [
        ...?(meta?['placeholders'] as Map<String, dynamic>?)?.keys,
      ];
      final base = _snake(key);
      final forms = _plural(value);
      if (forms == null) {
        result['${base}_$locale'] = _parts(value, names);
      } else {
        for (final MapEntry(key: form, value: text) in forms.entries) {
          result['${base}_${form}_$locale'] = _parts(text, names);
        }
      }
    }
  }
  return Map.fromEntries(
    result.entries.toList()..sort((a, b) => a.key.compareTo(b.key)),
  );
}

String toAndroidXml(Map<String, Parts> strings) {
  final out = StringBuffer()
    ..writeln('<?xml version="1.0" encoding="utf-8"?>')
    ..writeln(
      '<!-- Generated by tool/push_strings.dart from lib/l10n. Do not edit. -->',
    )
    ..writeln('<resources>');
  for (final MapEntry(:key, :value) in strings.entries) {
    final text = value.map((part) {
      if (part is int) return '%$part\$s';
      return (part as String)
          .replaceAll(r'\', r'\\')
          .replaceAll('&', '&amp;')
          .replaceAll('<', '&lt;')
          .replaceAll("'", r"\'")
          .replaceAll('"', r'\"')
          .replaceAll('%', '%%')
          .replaceAll('\n', r'\n');
    }).join();
    final safe = text.startsWith('@') || text.startsWith('?')
        ? '\\$text'
        : text;
    out.writeln('    <string name="$key">$safe</string>');
  }
  out.writeln('</resources>');
  return out.toString();
}

String toIosStrings(Map<String, Parts> strings) {
  final out = StringBuffer()
    ..writeln(
      '/* Generated by tool/push_strings.dart from lib/l10n. Do not edit. */',
    );
  for (final MapEntry(:key, :value) in strings.entries) {
    final text = value.map((part) {
      if (part is int) return '%$part\$@';
      return (part as String)
          .replaceAll(r'\', r'\\')
          .replaceAll('"', r'\"')
          .replaceAll('%', '%%')
          .replaceAll('\n', r'\n');
    }).join();
    out.writeln('"$key" = "$text";');
  }
  return out.toString();
}

/// The `app_<locale>.arb` files under [directory], by language.
Map<String, Map<String, dynamic>> readArbs([String directory = 'lib/l10n']) {
  final arbs = <String, Map<String, dynamic>>{};
  for (final file in Directory(directory).listSync().whereType<File>()) {
    final match = RegExp(r'app_(\w+)\.arb$').firstMatch(file.path);
    if (match == null) continue;
    arbs[match[1]!] =
        jsonDecode(file.readAsStringSync()) as Map<String, dynamic>;
  }
  return arbs;
}

void main() {
  final strings = pushStrings(readArbs());
  File(androidPath).writeAsStringSync(toAndroidXml(strings));
  File(iosPath).writeAsStringSync(toIosStrings(strings));
  stdout.writeln('${strings.length} push strings written.');
}

String _snake(String key) =>
    key.replaceAllMapped(RegExp('[A-Z]'), (m) => '_${m[0]!.toLowerCase()}');

/// `one` and `other` of a whole-message plural; null for plain text.
Map<String, String>? _plural(String message) {
  final match = RegExp(
    r'^\{\s*\w+\s*,\s*plural\s*,(.*)\}$',
    dotAll: true,
  ).firstMatch(message.trim());
  if (match == null) return null;
  final body = match[1]!;
  final forms = <String, String>{};
  var i = 0;
  while (true) {
    while (i < body.length && body[i].trim().isEmpty) {
      i++;
    }
    if (i >= body.length) break;
    final open = body.indexOf('{', i);
    if (open < 0) throw FormatException('Bad plural', message);
    final selector = body.substring(i, open).trim();
    var depth = 0;
    var close = open;
    for (; close < body.length; close++) {
      if (body[close] == '{') depth++;
      if (body[close] == '}' && --depth == 0) break;
    }
    if (depth != 0) throw FormatException('Unbalanced plural', message);
    final form = switch (selector) {
      '=1' || 'one' => 'one',
      'other' => 'other',
      _ => throw FormatException('Unsupported plural case $selector', message),
    };
    forms.putIfAbsent(form, () => body.substring(open + 1, close));
    i = close + 1;
  }
  if (!forms.containsKey('other')) {
    throw FormatException('Plural without other', message);
  }
  return forms;
}

Parts _parts(String text, List<String> names) {
  final parts = <Object>[];
  var last = 0;
  for (final match in RegExp(r'\{(\w+)\}').allMatches(text)) {
    final position = names.indexOf(match[1]!);
    if (position < 0) {
      throw FormatException('Unknown placeholder ${match[1]}', text);
    }
    if (match.start > last) parts.add(text.substring(last, match.start));
    parts.add(position + 1);
    last = match.end;
  }
  if (last < text.length) parts.add(text.substring(last));
  return parts;
}
